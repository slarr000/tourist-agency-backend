-- Сохраняет существующие бронирования и связывает только однозначные совпадения.
-- Выполнять после StoredProcedures.sql и CourseworkEnhancements.sql.
BEGIN;

ALTER TABLE public."Bookings" ADD COLUMN IF NOT EXISTS visit_id INTEGER;
CREATE INDEX IF NOT EXISTS ix_bookings_visit_id ON public."Bookings"(visit_id);

CREATE OR REPLACE FUNCTION public.coursework_validate_booking_visit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.visit_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public."Tourist Visits" v
        WHERE v.visit_id = NEW.visit_id AND v.tourist_id = NEW.tourist_id
          AND NEW.check_in_date <= v.departure_date AND NEW.check_out_date >= v.arrival_date
    ) THEN
        RAISE EXCEPTION 'Поездка должна принадлежать туристу и пересекаться с датами проживания.'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS coursework_booking_visit_guard ON public."Bookings";
CREATE TRIGGER coursework_booking_visit_guard
    BEFORE INSERT OR UPDATE OF visit_id, tourist_id, check_in_date, check_out_date
    ON public."Bookings" FOR EACH ROW
    EXECUTE FUNCTION public.coursework_validate_booking_visit();

CREATE OR REPLACE FUNCTION public.coursework_validate_visit_bookings()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF EXISTS (SELECT 1 FROM public."Bookings" b WHERE b.visit_id = OLD.visit_id) THEN
            RAISE EXCEPTION 'Сначала переназначьте или удалите связанные бронирования гостиницы.'
                USING ERRCODE = '23514';
        END IF;
        RETURN OLD;
    END IF;
    IF EXISTS (
        SELECT 1 FROM public."Bookings" b
        WHERE b.visit_id = OLD.visit_id
          AND (b.tourist_id <> NEW.tourist_id
               OR b.check_in_date > NEW.departure_date
               OR b.check_out_date < NEW.arrival_date)
    ) THEN
        RAISE EXCEPTION 'Изменение поездки противоречит связанному бронированию гостиницы.'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS coursework_visit_bookings_guard ON public."Tourist Visits";
CREATE TRIGGER coursework_visit_bookings_guard
    BEFORE UPDATE OF tourist_id, arrival_date, departure_date OR DELETE
    ON public."Tourist Visits" FOR EACH ROW
    EXECUTE FUNCTION public.coursework_validate_visit_bookings();

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_bookings_visit' AND conrelid = 'public."Bookings"'::regclass
    ) THEN
        ALTER TABLE public."Bookings" ADD CONSTRAINT fk_bookings_visit
            FOREIGN KEY (visit_id) REFERENCES public."Tourist Visits"(visit_id) ON DELETE RESTRICT;
    END IF;
END;
$$;

WITH matches AS (
    SELECT b.booking_id, MIN(v.visit_id) AS visit_id
    FROM public."Bookings" b
    JOIN public."Tourist Visits" v ON v.tourist_id = b.tourist_id
        AND b.check_in_date <= v.departure_date
        AND b.check_out_date >= v.arrival_date
    WHERE b.visit_id IS NULL
    GROUP BY b.booking_id
    HAVING COUNT(*) = 1
)
UPDATE public."Bookings" b SET visit_id = matches.visit_id
FROM matches WHERE b.booking_id = matches.booking_id AND b.visit_id IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_tourist_visits_visit_tourist
    ON public."Tourist Visits"(visit_id, tourist_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_tourist_children_child_tourist
    ON public."Tourist Children"(child_id, tourist_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_bookings_booking_visit_tourist
    ON public."Bookings"(booking_id, visit_id, tourist_id);

CREATE TABLE IF NOT EXISTS public."Child Visits" (
    child_visit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tourist_id INTEGER NOT NULL,
    visit_id INTEGER NOT NULL,
    child_id INTEGER NOT NULL,
    UNIQUE (visit_id, child_id),
    UNIQUE (visit_id, child_id, tourist_id),
    FOREIGN KEY (visit_id, tourist_id) REFERENCES public."Tourist Visits"(visit_id, tourist_id),
    FOREIGN KEY (child_id, tourist_id) REFERENCES public."Tourist Children"(child_id, tourist_id)
);

CREATE TABLE IF NOT EXISTS public."Child Bookings" (
    child_booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tourist_id INTEGER NOT NULL,
    visit_id INTEGER NOT NULL,
    booking_id INTEGER NOT NULL,
    child_id INTEGER NOT NULL,
    UNIQUE (booking_id, child_id),
    FOREIGN KEY (booking_id, visit_id, tourist_id)
        REFERENCES public."Bookings"(booking_id, visit_id, tourist_id),
    FOREIGN KEY (visit_id, child_id, tourist_id)
        REFERENCES public."Child Visits"(visit_id, child_id, tourist_id)
);

CREATE OR REPLACE FUNCTION public.coursework_flight_tourist_details(p_flight_number TEXT)
RETURNS TABLE (flight_number TEXT, flight_date DATE, full_name TEXT, category TEXT, has_visa BOOLEAN,
               hotel_name TEXT, room_number TEXT, cargo_type TEXT, places_count INTEGER,
               cargo_weight NUMERIC, volume_weight NUMERIC, tags TEXT, marking TEXT)
LANGUAGE sql STABLE AS $$
    WITH adult_flights AS (
        SELECT tourist_id, flight_id FROM public."Tourist Information" WHERE flight_id IS NOT NULL
        UNION SELECT tourist_id, flight_id FROM public."Tourist Visits"
    ), rows AS (
        SELECT f.flight_number::TEXT, f.flight_date,
               CONCAT_WS(' ', t.tourist_surname, t.tourist_name, t.tourist_patronymic)::TEXT AS full_name,
               t.category::TEXT, t.has_visa, h.hotel_name, h.room_number,
               c.cargo_type::TEXT, c.places_count, c.actual_weight::NUMERIC AS cargo_weight,
               c.volume_weight::NUMERIC, c.tags::TEXT, c.marking::TEXT
        FROM public."Flights" f
        JOIN adult_flights af ON af.flight_id = f.flight_id
        JOIN public."Tourist Information" t ON t.tourist_id = af.tourist_id
        LEFT JOIN LATERAL (
            SELECT STRING_AGG(FORMAT('%s (номер %s, %s — %s)', h.hotel_name, b.room_number, b.check_in_date, b.check_out_date), '; ' ORDER BY b.check_in_date)::TEXT AS hotel_name,
                   STRING_AGG(DISTINCT b.room_number, ', ' ORDER BY b.room_number)::TEXT AS room_number
            FROM public."Bookings" b JOIN public."Hotels" h ON h.hotel_id = b.hotel_id
            JOIN public."Tourist Visits" v ON v.visit_id = b.visit_id
            WHERE b.tourist_id = t.tourist_id AND v.flight_id = f.flight_id
        ) h ON TRUE
        LEFT JOIN public."Tourist Cargo" c ON c.tourist_id = t.tourist_id AND c.flight_id = f.flight_id
        WHERE f.flight_number = BTRIM(p_flight_number)
        UNION ALL
        SELECT f.flight_number::TEXT, f.flight_date,
               CONCAT_WS(' ', child.last_name, child.first_name, child.patronymic)::TEXT,
               'Ребёнок'::TEXT, NULL::BOOLEAN, h.hotel_name, h.room_number,
               NULL::TEXT, NULL::INTEGER, NULL::NUMERIC, NULL::NUMERIC, NULL::TEXT, NULL::TEXT
        FROM public."Flights" f
        JOIN (SELECT DISTINCT visit.flight_id, cv.child_id
              FROM public."Child Visits" cv JOIN public."Tourist Visits" visit ON visit.visit_id = cv.visit_id) passengers
          ON passengers.flight_id = f.flight_id
        JOIN public."Tourist Children" child ON child.child_id = passengers.child_id
        LEFT JOIN LATERAL (
            SELECT STRING_AGG(FORMAT('%s (номер %s, %s — %s)', h.hotel_name, b.room_number, b.check_in_date, b.check_out_date), '; ' ORDER BY b.check_in_date)::TEXT AS hotel_name,
                   STRING_AGG(DISTINCT b.room_number, ', ' ORDER BY b.room_number)::TEXT AS room_number
            FROM public."Child Bookings" cb JOIN public."Bookings" b ON b.booking_id = cb.booking_id
            JOIN public."Hotels" h ON h.hotel_id = b.hotel_id
            JOIN public."Tourist Visits" visit ON visit.visit_id = cb.visit_id
            WHERE cb.child_id = child.child_id AND visit.flight_id = f.flight_id
        ) h ON TRUE
        WHERE f.flight_number = BTRIM(p_flight_number)
    )
    SELECT * FROM rows ORDER BY flight_date, flight_number, full_name;
$$;

COMMIT;

