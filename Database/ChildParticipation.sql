CREATE OR REPLACE FUNCTION public.coursework_hotel_check_in_with_children(p_hotel_name TEXT DEFAULT NULL, p_category TEXT DEFAULT NULL)
RETURNS TABLE (hotel_name TEXT, tourist_full_name TEXT, category TEXT, check_in_date DATE,
               check_out_date DATE, room_number TEXT, accompanying_children TEXT, children_count BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT h.hotel_name::TEXT,
           CONCAT_WS(' ', t.tourist_surname, t.tourist_name, t.tourist_patronymic)::TEXT,
           t.category::TEXT, b.check_in_date, b.check_out_date, b.room_number::TEXT,
           COALESCE(children.names, 'Нет подтверждённых')::TEXT, COALESCE(children.child_count, 0)::BIGINT
    FROM public."Bookings" b
    JOIN public."Hotels" h ON h.hotel_id = b.hotel_id
    JOIN public."Tourist Information" t ON t.tourist_id = b.tourist_id
    LEFT JOIN LATERAL (
        SELECT STRING_AGG(CONCAT_WS(' ', c.last_name, c.first_name, c.patronymic), ', ' ORDER BY c.last_name, c.first_name) AS names,
               COUNT(*)::BIGINT AS child_count
        FROM public."Child Bookings" cb
        JOIN public."Tourist Children" c ON c.child_id = cb.child_id
        WHERE cb.booking_id = b.booking_id
    ) children ON TRUE
    WHERE (NULLIF(BTRIM(p_hotel_name), '') IS NULL OR h.hotel_name ILIKE BTRIM(p_hotel_name))
      AND (NULLIF(BTRIM(p_category), '') IS NULL OR t.category = BTRIM(p_category))
    ORDER BY h.hotel_name, b.check_in_date, t.tourist_surname;
$$;

CREATE OR REPLACE FUNCTION public.coursework_hotel_occupancy(p_start_date DATE DEFAULT NULL, p_end_date DATE DEFAULT NULL, p_category TEXT DEFAULT NULL)
RETURNS TABLE (hotel_name TEXT, country TEXT, occupied_rooms BIGINT, resident_tourists BIGINT, resident_children BIGINT, total_residents BIGINT)
LANGUAGE sql STABLE AS $$
    WITH occupied AS (
        SELECT h.hotel_id, h.hotel_name::TEXT AS hotel_name, h.country::TEXT AS country,
               b.booking_id, b.room_number, t.tourist_id
        FROM public."Bookings" b
        JOIN public."Hotels" h ON h.hotel_id = b.hotel_id
        JOIN public."Tourist Information" t ON t.tourist_id = b.tourist_id
        WHERE (p_start_date IS NULL OR b.check_out_date >= p_start_date)
          AND (p_end_date IS NULL OR b.check_in_date <= p_end_date)
          AND (NULLIF(BTRIM(p_category), '') IS NULL OR t.category = BTRIM(p_category))
    )
    SELECT o.hotel_name, o.country, COUNT(DISTINCT (o.hotel_id, o.room_number))::BIGINT,
           COUNT(DISTINCT o.tourist_id)::BIGINT, COUNT(DISTINCT cb.child_id)::BIGINT,
           (COUNT(DISTINCT o.tourist_id) + COUNT(DISTINCT cb.child_id))::BIGINT
    FROM occupied o LEFT JOIN public."Child Bookings" cb ON cb.booking_id = o.booking_id
    GROUP BY o.hotel_id, o.hotel_name, o.country
    ORDER BY COUNT(DISTINCT (o.hotel_id, o.room_number)) DESC, o.hotel_name;
$$;

CREATE OR REPLACE FUNCTION public.coursework_flight_load(p_start_date DATE, p_end_date DATE, p_flight_number TEXT DEFAULT NULL)
RETURNS TABLE (flight_id INTEGER, flight_number TEXT, flight_date DATE, flight_type TEXT, seat_capacity INTEGER,
               passenger_count BIGINT, available_seats BIGINT, cargo_places BIGINT, actual_weight NUMERIC, volume_weight NUMERIC)
LANGUAGE sql STABLE AS $$
    WITH adult_flights AS (
        SELECT tourist_id, flight_id FROM public."Tourist Information" WHERE flight_id IS NOT NULL
        UNION SELECT tourist_id, flight_id FROM public."Tourist Visits"
    ), passengers AS (
        SELECT flight_id, COUNT(*)::BIGINT AS passenger_count FROM (
            SELECT flight_id, 'adult' AS kind, tourist_id AS person_id FROM adult_flights
            UNION
            SELECT v.flight_id, 'child', cv.child_id FROM public."Child Visits" cv
            JOIN public."Tourist Visits" v ON v.visit_id = cv.visit_id
        ) people GROUP BY flight_id
    ), cargo AS (
        SELECT c.flight_id, SUM(c.places_count)::BIGINT AS places,
               SUM(c.actual_weight)::NUMERIC AS weight, SUM(c.volume_weight)::NUMERIC AS volume
        FROM public."Tourist Cargo" c GROUP BY c.flight_id
    )
    SELECT f.flight_id, f.flight_number::TEXT, f.flight_date, f.flight_type::TEXT, f.seat_capacity,
           COALESCE(p.passenger_count, 0)::BIGINT,
           GREATEST(f.seat_capacity - COALESCE(p.passenger_count, 0), 0)::BIGINT,
           COALESCE(c.places, 0)::BIGINT, COALESCE(c.weight, 0)::NUMERIC, COALESCE(c.volume, 0)::NUMERIC
    FROM public."Flights" f
    LEFT JOIN passengers p ON p.flight_id = f.flight_id
    LEFT JOIN cargo c ON c.flight_id = f.flight_id
    WHERE f.flight_date BETWEEN p_start_date AND p_end_date
      AND (NULLIF(BTRIM(p_flight_number), '') IS NULL OR f.flight_number = BTRIM(p_flight_number))
    ORDER BY f.flight_date, f.flight_number;
$$;

CREATE OR REPLACE FUNCTION public.coursework_flight_tourist_details(p_flight_number TEXT)
RETURNS TABLE (flight_number TEXT, flight_date DATE, full_name TEXT, category TEXT, has_visa BOOLEAN,
               hotel_name TEXT, room_number TEXT, cargo_type TEXT, places_count INTEGER,
               cargo_weight NUMERIC, volume_weight NUMERIC, tags TEXT, marking TEXT)
LANGUAGE sql STABLE AS $$
    WITH adult_flights AS (
        SELECT tourist_id, flight_id FROM public."Tourist Information" WHERE flight_id IS NOT NULL
        UNION SELECT tourist_id, flight_id FROM public."Tourist Visits"
    ), rows AS (
        SELECT f.flight_number::TEXT, f.flight_date,
               CONCAT_WS(' ', t.tourist_surname, t.tourist_name, t.tourist_patronymic)::TEXT AS full_name,
               t.category::TEXT, t.has_visa, h.hotel_name, h.room_number,
               c.cargo_type::TEXT, c.places_count, c.actual_weight::NUMERIC AS cargo_weight,
               c.volume_weight::NUMERIC, c.tags::TEXT, c.marking::TEXT
        FROM public."Flights" f
        JOIN adult_flights af ON af.flight_id = f.flight_id
        JOIN public."Tourist Information" t ON t.tourist_id = af.tourist_id
        LEFT JOIN LATERAL (
            SELECT STRING_AGG(FORMAT('%s (номер %s, %s — %s)', h.hotel_name, b.room_number, b.check_in_date, b.check_out_date), '; ' ORDER BY b.check_in_date)::TEXT AS hotel_name,
                   STRING_AGG(DISTINCT b.room_number, ', ' ORDER BY b.room_number)::TEXT AS room_number
            FROM public."Bookings" b JOIN public."Hotels" h ON h.hotel_id = b.hotel_id
            JOIN public."Tourist Visits" v ON v.visit_id = b.visit_id
            WHERE b.tourist_id = t.tourist_id AND v.flight_id = f.flight_id
        ) h ON TRUE
        LEFT JOIN public."Tourist Cargo" c ON c.tourist_id = t.tourist_id AND c.flight_id = f.flight_id
        WHERE f.flight_number = BTRIM(p_flight_number)
        UNION ALL
        SELECT f.flight_number::TEXT, f.flight_date,
               CONCAT_WS(' ', child.last_name, child.first_name, child.patronymic)::TEXT,
               'Ребёнок'::TEXT, NULL::BOOLEAN, h.hotel_name, h.room_number,
               NULL::TEXT, NULL::INTEGER, NULL::NUMERIC, NULL::NUMERIC, NULL::TEXT, NULL::TEXT
        FROM public."Flights" f
        JOIN (SELECT DISTINCT visit.flight_id, cv.child_id
              FROM public."Child Visits" cv JOIN public."Tourist Visits" visit ON visit.visit_id = cv.visit_id) passengers
          ON passengers.flight_id = f.flight_id
        JOIN public."Tourist Children" child ON child.child_id = passengers.child_id
        LEFT JOIN LATERAL (
            SELECT STRING_AGG(FORMAT('%s (номер %s, %s — %s)', h.hotel_name, b.room_number, b.check_in_date, b.check_out_date), '; ' ORDER BY b.check_in_date)::TEXT AS hotel_name,
                   STRING_AGG(DISTINCT b.room_number, ', ' ORDER BY b.room_number)::TEXT AS room_number
            FROM public."Child Bookings" cb JOIN public."Bookings" b ON b.booking_id = cb.booking_id
            JOIN public."Hotels" h ON h.hotel_id = b.hotel_id
            JOIN public."Tourist Visits" visit ON visit.visit_id = cb.visit_id
            WHERE cb.child_id = child.child_id AND visit.flight_id = f.flight_id
        ) h ON TRUE
        WHERE f.flight_number = BTRIM(p_flight_number)
    )
    SELECT * FROM rows ORDER BY flight_date, flight_number, full_name;
$$;

CREATE OR REPLACE FUNCTION public.getfamilytoursreport()
RETURNS TABLE (parent_full_name TEXT, child_name TEXT, child_age INTEGER, flight_number TEXT)
LANGUAGE sql STABLE AS $$
    SELECT CONCAT(t.tourist_surname, ' ', t.tourist_name)::TEXT,
           CONCAT(child.last_name, ' ', child.first_name)::TEXT,
           EXTRACT(YEAR FROM AGE(child.date_of_birth))::INTEGER AS child_age,
           f.flight_number::TEXT
    FROM public."Tourist Information" t
    JOIN public."Tourist Children" child ON child.tourist_id = t.tourist_id
    LEFT JOIN public."Child Visits" cv ON cv.child_id = child.child_id
    LEFT JOIN public."Tourist Visits" v ON v.visit_id = cv.visit_id
    LEFT JOIN public."Flights" f ON f.flight_id = v.flight_id
    ORDER BY f.flight_date, child_age;
$$;

