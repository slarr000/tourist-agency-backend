CREATE UNIQUE INDEX IF NOT EXISTS ux_tourist_visits_visit_tourist
    ON public."Tourist Visits"(visit_id, tourist_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_tourist_children_child_tourist
    ON public."Tourist Children"(child_id, tourist_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_bookings_booking_visit_tourist
    ON public."Bookings"(booking_id, visit_id, tourist_id);

CREATE TABLE IF NOT EXISTS public."Child Visits" (
    child_visit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tourist_id INTEGER NOT NULL,
    visit_id INTEGER NOT NULL,
    child_id INTEGER NOT NULL,
    UNIQUE (visit_id, child_id),
    UNIQUE (visit_id, child_id, tourist_id),
    FOREIGN KEY (visit_id, tourist_id) REFERENCES public."Tourist Visits"(visit_id, tourist_id),
    FOREIGN KEY (child_id, tourist_id) REFERENCES public."Tourist Children"(child_id, tourist_id)
);

CREATE TABLE IF NOT EXISTS public."Child Bookings" (
    child_booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tourist_id INTEGER NOT NULL,
    visit_id INTEGER NOT NULL,
    booking_id INTEGER NOT NULL,
    child_id INTEGER NOT NULL,
    UNIQUE (booking_id, child_id),
    FOREIGN KEY (booking_id, visit_id, tourist_id)
        REFERENCES public."Bookings"(booking_id, visit_id, tourist_id),
    FOREIGN KEY (visit_id, child_id, tourist_id)
        REFERENCES public."Child Visits"(visit_id, child_id, tourist_id)
);

